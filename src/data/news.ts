export function sortNewsByDate<T extends { date: string; id: string }>(items: T[]): T[] {
  return [...items].sort(
    (a, b) => b.date.localeCompare(a.date) || Number(b.id) - Number(a.id)
  );
}

export const newsItems = sortNewsByDate(newsItemsSource);

export function getNewsById(id: string) {
  return newsItems.find((n) => n.id === id);
}

export function paginateNews(items: NewsItem[], page: number, pageSize = 10) {
  const start = (page - 1) * pageSize;
  return {
    items: items.slice(start, start + pageSize),
    total: items.length,
    totalPages: Math.ceil(items.length / pageSize),
    page,
    pageSize,
  };
}
